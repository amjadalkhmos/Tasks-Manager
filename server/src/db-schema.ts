import type { Dialect, Queryable } from "./db.js";

/**
 * The schema, written once and rendered for each database. Timestamps are ISO-8601 TEXT in both, so values and
 * comparisons behave identically. Booleans are 0/1 integers for the same reason.
 *
 * Tables are listed in dependency order (PostgreSQL requires a referenced table to exist first).
 */
export function schemaSql(d: Dialect): string {
  const pg = d === "postgres";
  const ID = pg ? "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" : "INTEGER PRIMARY KEY";
  const REAL = pg ? "DOUBLE PRECISION" : "REAL";
  // "YYYY-MM-DD HH:MM:SS" (UTC) and "YYYY-MM-DDTHH:MM:SS.mmmZ" respectively
  const NOW = pg ? "(to_char(timezone('UTC', now()), 'YYYY-MM-DD HH24:MI:SS'))" : "(datetime('now'))";
  const NOW_ISO = pg
    ? `(to_char(timezone('UTC', now()), 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'))`
    : "(strftime('%Y-%m-%dT%H:%M:%fZ','now'))";

  return `
CREATE TABLE IF NOT EXISTS users (
  id ${ID},
  email TEXT NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  name TEXT,
  created_at TEXT NOT NULL DEFAULT ${NOW}
);

CREATE TABLE IF NOT EXISTS workspaces (
  id ${ID},
  name TEXT NOT NULL,
  created_by INTEGER NOT NULL REFERENCES users(id),
  created_at TEXT NOT NULL DEFAULT ${NOW}
);
CREATE TABLE IF NOT EXISTS workspace_members (
  workspace_id INTEGER NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  role TEXT NOT NULL CHECK (role IN ('owner','admin','member','viewer')),
  joined_at TEXT NOT NULL DEFAULT ${NOW},
  PRIMARY KEY (workspace_id, user_id)
);
CREATE TABLE IF NOT EXISTS workspace_invites (
  id ${ID},
  workspace_id INTEGER NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
  email TEXT NOT NULL,
  role TEXT NOT NULL CHECK (role IN ('admin','member','viewer')),
  invited_by INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  created_at TEXT NOT NULL DEFAULT ${NOW},
  UNIQUE (workspace_id, email)
);

CREATE TABLE IF NOT EXISTS projects (
  id ${ID},
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  color TEXT NOT NULL DEFAULT '#4f46e5',
  workspace_id INTEGER REFERENCES workspaces(id),
  description TEXT NOT NULL DEFAULT '',
  stage TEXT NOT NULL DEFAULT 'active' CHECK (stage IN ('planning','active','on_hold','completed','archived')),
  lead_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  start_date TEXT,
  target_date TEXT,
  type TEXT NOT NULL DEFAULT 'initiative' CHECK (type IN ('delivery','pipeline','initiative','support')),
  currency TEXT NOT NULL DEFAULT 'USD',
  first_response_hours INTEGER,
  resolution_hours INTEGER,
  intake_token TEXT
);
-- Task statuses. Every status belongs to a category (todo, doing or done), which is what the app's logic (completion,
-- recurrence, dependencies, progress) uses; the name and colour are the team's own. A status belongs either to one
-- project, or to a workspace (used by the workspace's projects that don't define their own). With none defined, the
-- built-in To do / Doing / Done apply.
CREATE TABLE IF NOT EXISTS statuses (
  id ${ID},
  workspace_id INTEGER REFERENCES workspaces(id) ON DELETE CASCADE,
  project_id INTEGER REFERENCES projects(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  category TEXT NOT NULL CHECK (category IN ('todo','doing','done')),
  color TEXT NOT NULL DEFAULT '#64748b',
  position INTEGER NOT NULL DEFAULT 0,
  probability INTEGER CHECK (probability BETWEEN 0 AND 100),
  CHECK ((workspace_id IS NULL AND project_id IS NOT NULL) OR (workspace_id IS NOT NULL AND project_id IS NULL))
);
-- A project's history: progress updates (with a health rating) and stage changes (with an optional note).
CREATE TABLE IF NOT EXISTS project_updates (
  id ${ID},
  project_id INTEGER NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  kind TEXT NOT NULL CHECK (kind IN ('update','stage')),
  stage TEXT,
  health TEXT CHECK (health IN ('on_track','at_risk','off_track')),
  body TEXT NOT NULL DEFAULT '',
  created_at TEXT NOT NULL DEFAULT ${NOW_ISO}
);
-- A milestone is a dated checkpoint, not a group of tasks. due_date is the forecast (the current best guess);
-- baseline_date is what was first promised, so slippage can be seen. outcome is a decision made by the project's lead or
-- a manager (achieved or missed), never worked out from the tasks. See ADDED_COLUMNS for the rest.
CREATE TABLE IF NOT EXISTS milestones (
  id ${ID},
  project_id INTEGER NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  due_date TEXT,
  completed_at TEXT,
  position INTEGER NOT NULL DEFAULT 0
);
-- Each change of a milestone's forecast date, with the reason given.
CREATE TABLE IF NOT EXISTS milestone_moves (
  id ${ID},
  milestone_id INTEGER NOT NULL REFERENCES milestones(id) ON DELETE CASCADE,
  user_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  from_date TEXT,
  to_date TEXT,
  reason TEXT NOT NULL DEFAULT '',
  created_at TEXT NOT NULL DEFAULT ${NOW_ISO}
);
-- "milestone_id can't be achieved before depends_on_id": both belong to the same project.
CREATE TABLE IF NOT EXISTS milestone_deps (
  milestone_id INTEGER NOT NULL REFERENCES milestones(id) ON DELETE CASCADE,
  depends_on_id INTEGER NOT NULL REFERENCES milestones(id) ON DELETE CASCADE,
  PRIMARY KEY (milestone_id, depends_on_id),
  CHECK (milestone_id != depends_on_id)
);
CREATE TABLE IF NOT EXISTS tags (
  id ${ID},
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  UNIQUE (user_id, name)
);
CREATE TABLE IF NOT EXISTS tasks (
  id ${ID},
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  project_id INTEGER REFERENCES projects(id) ON DELETE SET NULL,
  parent_id INTEGER REFERENCES tasks(id) ON DELETE CASCADE,
  title TEXT NOT NULL,
  notes TEXT NOT NULL DEFAULT '',
  priority INTEGER NOT NULL DEFAULT 0 CHECK (priority BETWEEN 0 AND 3),
  status TEXT NOT NULL DEFAULT 'todo' CHECK (status IN ('todo','doing','done')),
  due_at TEXT,
  remind_at TEXT,
  reminded_at TEXT,
  ack INTEGER NOT NULL DEFAULT 0,
  recurrence_rule TEXT,
  completed_at TEXT,
  created_at TEXT NOT NULL DEFAULT ${NOW},
  position ${REAL} NOT NULL DEFAULT 0,
  estimate_min INTEGER,
  assignee_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  status_id INTEGER REFERENCES statuses(id) ON DELETE SET NULL,
  start_at TEXT,
  milestone_id INTEGER REFERENCES milestones(id) ON DELETE SET NULL,
  value ${REAL},
  requester_name TEXT,
  requester_email TEXT,
  source TEXT NOT NULL DEFAULT 'internal' CHECK (source IN ('internal','form','email')),
  ticket_no INTEGER,
  first_response_at TEXT
);
CREATE TABLE IF NOT EXISTS task_tags (
  task_id INTEGER NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,
  tag_id INTEGER NOT NULL REFERENCES tags(id) ON DELETE CASCADE,
  PRIMARY KEY (task_id, tag_id)
);
CREATE TABLE IF NOT EXISTS task_deps (
  task_id INTEGER NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,
  blocked_by_id INTEGER NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,
  PRIMARY KEY (task_id, blocked_by_id),
  CHECK (task_id != blocked_by_id)
);
CREATE TABLE IF NOT EXISTS checklist_items (
  id ${ID},
  task_id INTEGER NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,
  text TEXT NOT NULL,
  done INTEGER NOT NULL DEFAULT 0,
  position INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS saved_filters (
  id ${ID},
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  query_json TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS time_entries (
  id ${ID},
  task_id INTEGER NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  started_at TEXT NOT NULL,
  ended_at TEXT
);

CREATE TABLE IF NOT EXISTS integrations (
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  provider TEXT NOT NULL,
  tokens_enc TEXT NOT NULL,
  account TEXT,
  settings_json TEXT NOT NULL DEFAULT '{}',
  last_sync TEXT,
  PRIMARY KEY (user_id, provider)
);
-- One Google Calendar event per task with a due date. state 'removed' = the user deleted the event on Google's side.
CREATE TABLE IF NOT EXISTS gcal_links (
  task_id INTEGER PRIMARY KEY REFERENCES tasks(id) ON DELETE CASCADE,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  event_id TEXT NOT NULL,
  due_synced TEXT NOT NULL,
  state TEXT NOT NULL DEFAULT 'active' CHECK (state IN ('active','removed'))
);
CREATE TABLE IF NOT EXISTS gmail_seen (
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  message_id TEXT NOT NULL,
  task_id INTEGER,
  PRIMARY KEY (user_id, message_id)
);

CREATE TABLE IF NOT EXISTS comments (
  id ${ID},
  task_id INTEGER NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  body TEXT NOT NULL,
  created_at TEXT NOT NULL DEFAULT ${NOW_ISO},
  edited_at TEXT,
  requester TEXT
);
CREATE TABLE IF NOT EXISTS comment_mentions (
  comment_id INTEGER NOT NULL REFERENCES comments(id) ON DELETE CASCADE,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  PRIMARY KEY (comment_id, user_id)
);
-- History is kept after a task is deleted, so task_id has no foreign key; the title lives in detail_json.
CREATE TABLE IF NOT EXISTS activity (
  id ${ID},
  workspace_id INTEGER NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
  task_id INTEGER,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  kind TEXT NOT NULL,
  detail_json TEXT NOT NULL DEFAULT '{}',
  created_at TEXT NOT NULL DEFAULT ${NOW_ISO}
);
CREATE TABLE IF NOT EXISTS alerts (
  id ${ID},
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  kind TEXT NOT NULL,
  actor_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  task_id INTEGER,
  workspace_id INTEGER REFERENCES workspaces(id) ON DELETE CASCADE,
  title TEXT NOT NULL DEFAULT '',
  created_at TEXT NOT NULL DEFAULT ${NOW_ISO},
  read_at TEXT
);

-- Meetings live in the app. A meeting is private to its creator (workspace_id NULL) or shared with a workspace, and can
-- be linked to any number of tasks in the same place. source/external_* are reserved for calendars: a meeting that comes
-- from Google Calendar will have source 'google' plus the event's id and link, so syncing can update it instead of
-- duplicating it.
CREATE TABLE IF NOT EXISTS meetings (
  id ${ID},
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  workspace_id INTEGER REFERENCES workspaces(id) ON DELETE CASCADE,
  title TEXT NOT NULL,
  notes TEXT NOT NULL DEFAULT '',
  starts_at TEXT NOT NULL,
  ends_at TEXT NOT NULL,
  location TEXT NOT NULL DEFAULT '',
  url TEXT NOT NULL DEFAULT '',
  source TEXT NOT NULL DEFAULT 'local' CHECK (source IN ('local','google')),
  external_id TEXT,
  external_url TEXT,
  created_at TEXT NOT NULL DEFAULT ${NOW_ISO}
);
CREATE TABLE IF NOT EXISTS meeting_tasks (
  meeting_id INTEGER NOT NULL REFERENCES meetings(id) ON DELETE CASCADE,
  task_id INTEGER NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,
  PRIMARY KEY (meeting_id, task_id)
);

-- Sales. Everything here belongs to a workspace and has an owner (a user, or NULL = unassigned). Who sees what is decided
-- by sales_access: a row says "user_id may see (level 'view') or work on (level 'edit') the records owned by owner_id",
-- and a row with owner_id NULL covers unassigned records. Workspace admins and owners see everything.
CREATE TABLE IF NOT EXISTS sales_access (
  id ${ID},
  workspace_id INTEGER NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  owner_id INTEGER REFERENCES users(id) ON DELETE CASCADE,
  level TEXT NOT NULL CHECK (level IN ('view','edit'))
);
CREATE TABLE IF NOT EXISTS pipelines (
  id ${ID},
  workspace_id INTEGER NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  currency TEXT NOT NULL DEFAULT 'USD',
  position INTEGER NOT NULL DEFAULT 0
);
-- kind says what a stage means: a deal in an 'open' stage is still being worked, 'won' and 'lost' close it.
CREATE TABLE IF NOT EXISTS pipeline_stages (
  id ${ID},
  pipeline_id INTEGER NOT NULL REFERENCES pipelines(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  color TEXT NOT NULL DEFAULT '#64748b',
  position INTEGER NOT NULL DEFAULT 0,
  probability INTEGER NOT NULL DEFAULT 0 CHECK (probability BETWEEN 0 AND 100),
  kind TEXT NOT NULL DEFAULT 'open' CHECK (kind IN ('open','won','lost'))
);
CREATE TABLE IF NOT EXISTS accounts (
  id ${ID},
  workspace_id INTEGER NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
  owner_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  name TEXT NOT NULL,
  website TEXT NOT NULL DEFAULT '',
  domain TEXT NOT NULL DEFAULT '',
  industry TEXT NOT NULL DEFAULT '',
  size TEXT NOT NULL DEFAULT '',
  phone TEXT NOT NULL DEFAULT '',
  status TEXT NOT NULL DEFAULT 'prospect' CHECK (status IN ('prospect','customer','churned')),
  notes TEXT NOT NULL DEFAULT '',
  created_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
  created_at TEXT NOT NULL DEFAULT ${NOW_ISO}
);
-- A contact follows its account's owner (kept in step by the server), so one rule decides who sees both.
CREATE TABLE IF NOT EXISTS contacts (
  id ${ID},
  workspace_id INTEGER NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
  account_id INTEGER REFERENCES accounts(id) ON DELETE SET NULL,
  owner_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  name TEXT NOT NULL,
  email TEXT NOT NULL DEFAULT '',
  phone TEXT NOT NULL DEFAULT '',
  job_title TEXT NOT NULL DEFAULT '',
  notes TEXT NOT NULL DEFAULT '',
  created_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
  created_at TEXT NOT NULL DEFAULT ${NOW_ISO}
);
CREATE TABLE IF NOT EXISTS leads (
  id ${ID},
  workspace_id INTEGER NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
  owner_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  name TEXT NOT NULL,
  email TEXT NOT NULL DEFAULT '',
  phone TEXT NOT NULL DEFAULT '',
  company TEXT NOT NULL DEFAULT '',
  job_title TEXT NOT NULL DEFAULT '',
  source TEXT NOT NULL DEFAULT 'manual' CHECK (source IN ('manual','form','import','other')),
  source_detail TEXT NOT NULL DEFAULT '',
  status TEXT NOT NULL DEFAULT 'new' CHECK (status IN ('new','working','qualified','disqualified')),
  disqualified_reason TEXT NOT NULL DEFAULT '',
  notes TEXT NOT NULL DEFAULT '',
  account_id INTEGER REFERENCES accounts(id) ON DELETE SET NULL,
  contact_id INTEGER REFERENCES contacts(id) ON DELETE SET NULL,
  deal_id INTEGER,
  created_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
  created_at TEXT NOT NULL DEFAULT ${NOW_ISO},
  last_activity_at TEXT NOT NULL DEFAULT ${NOW_ISO},
  qualified_at TEXT
);
CREATE TABLE IF NOT EXISTS deals (
  id ${ID},
  workspace_id INTEGER NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
  pipeline_id INTEGER NOT NULL REFERENCES pipelines(id) ON DELETE CASCADE,
  stage_id INTEGER NOT NULL REFERENCES pipeline_stages(id),
  owner_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  account_id INTEGER REFERENCES accounts(id),
  contact_id INTEGER REFERENCES contacts(id) ON DELETE SET NULL,
  title TEXT NOT NULL,
  value ${REAL},
  expected_close TEXT,
  closed_at TEXT,
  lost_reason TEXT NOT NULL DEFAULT '',
  notes TEXT NOT NULL DEFAULT '',
  created_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
  created_at TEXT NOT NULL DEFAULT ${NOW_ISO},
  stage_changed_at TEXT NOT NULL DEFAULT ${NOW_ISO},
  last_activity_at TEXT NOT NULL DEFAULT ${NOW_ISO}
);
-- Calls, emails, meetings and notes logged against a record. 'system' entries are written by the app itself (a stage
-- change, an owner change). Exactly one of the four record columns is set.
CREATE TABLE IF NOT EXISTS sales_activities (
  id ${ID},
  workspace_id INTEGER NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
  user_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  kind TEXT NOT NULL CHECK (kind IN ('call','email','meeting','note','system')),
  subject TEXT NOT NULL DEFAULT '',
  body TEXT NOT NULL DEFAULT '',
  duration_min INTEGER,
  occurred_at TEXT NOT NULL,
  lead_id INTEGER REFERENCES leads(id) ON DELETE CASCADE,
  deal_id INTEGER REFERENCES deals(id) ON DELETE CASCADE,
  account_id INTEGER REFERENCES accounts(id) ON DELETE CASCADE,
  contact_id INTEGER REFERENCES contacts(id) ON DELETE CASCADE,
  created_at TEXT NOT NULL DEFAULT ${NOW_ISO}
);
-- A public "contact us" form. Each submission becomes an unassigned lead; the token is the form's secret address.
CREATE TABLE IF NOT EXISTS lead_forms (
  id ${ID},
  workspace_id INTEGER NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  token TEXT NOT NULL,
  enabled INTEGER NOT NULL DEFAULT 1,
  created_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
  created_at TEXT NOT NULL DEFAULT ${NOW_ISO}
);
`;
}

