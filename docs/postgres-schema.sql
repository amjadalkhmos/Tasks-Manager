-- Database schema for PostgreSQL.
-- You do NOT need to run this: the app creates and upgrades these tables itself when it starts with DATABASE_URL set.
-- Run it by hand only if you prefer to. It is safe to run more than once, on an empty database or on one created by an
-- earlier version: tables are created if missing, columns added since are added, then indexes are created.
-- Generated from server/src/db-schema.ts.

-- 1. Tables
CREATE TABLE IF NOT EXISTS users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email TEXT NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  name TEXT,
  created_at TEXT NOT NULL DEFAULT (to_char(timezone('UTC', now()), 'YYYY-MM-DD HH24:MI:SS'))
);

CREATE TABLE IF NOT EXISTS workspaces (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  created_by INTEGER NOT NULL REFERENCES users(id),
  created_at TEXT NOT NULL DEFAULT (to_char(timezone('UTC', now()), 'YYYY-MM-DD HH24:MI:SS'))
);
CREATE TABLE IF NOT EXISTS workspace_members (
  workspace_id INTEGER NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  role TEXT NOT NULL CHECK (role IN ('owner','admin','member','viewer')),
  joined_at TEXT NOT NULL DEFAULT (to_char(timezone('UTC', now()), 'YYYY-MM-DD HH24:MI:SS')),
  PRIMARY KEY (workspace_id, user_id)
);
CREATE TABLE IF NOT EXISTS workspace_invites (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id INTEGER NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
  email TEXT NOT NULL,
  role TEXT NOT NULL CHECK (role IN ('admin','member','viewer')),
  invited_by INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  created_at TEXT NOT NULL DEFAULT (to_char(timezone('UTC', now()), 'YYYY-MM-DD HH24:MI:SS')),
  UNIQUE (workspace_id, email)
);

CREATE TABLE IF NOT EXISTS projects (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  color TEXT NOT NULL DEFAULT '#4f46e5',
  workspace_id INTEGER REFERENCES workspaces(id),
  description TEXT NOT NULL DEFAULT '',
  stage TEXT NOT NULL DEFAULT 'active' CHECK (stage IN ('planning','active','on_hold','completed','archived')),
  lead_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  start_date TEXT,
  target_date TEXT,
  type TEXT NOT NULL DEFAULT 'initiative' CHECK (type IN ('delivery','pipeline','initiative','support')),
  currency TEXT NOT NULL DEFAULT 'USD',
  first_response_hours INTEGER,
  resolution_hours INTEGER,
  intake_token TEXT
);
-- Task statuses. Every status belongs to a category (todo, doing or done), which is what the app's logic (completion,
-- recurrence, dependencies, progress) uses; the name and colour are the team's own. A status belongs either to one
-- project, or to a workspace (used by the workspace's projects that don't define their own). With none defined, the
-- built-in To do / Doing / Done apply.
CREATE TABLE IF NOT EXISTS statuses (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id INTEGER REFERENCES workspaces(id) ON DELETE CASCADE,
  project_id INTEGER REFERENCES projects(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  category TEXT NOT NULL CHECK (category IN ('todo','doing','done')),
  color TEXT NOT NULL DEFAULT '#64748b',
  position INTEGER NOT NULL DEFAULT 0,
  probability INTEGER CHECK (probability BETWEEN 0 AND 100),
  CHECK ((workspace_id IS NULL AND project_id IS NOT NULL) OR (workspace_id IS NOT NULL AND project_id IS NULL))
);
-- A project's history: progress updates (with a health rating) and stage changes (with an optional note).
CREATE TABLE IF NOT EXISTS project_updates (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id INTEGER NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  kind TEXT NOT NULL CHECK (kind IN ('update','stage')),
  stage TEXT,
  health TEXT CHECK (health IN ('on_track','at_risk','off_track')),
  body TEXT NOT NULL DEFAULT '',
  created_at TEXT NOT NULL DEFAULT (to_char(timezone('UTC', now()), 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'))
);
-- A milestone is a dated checkpoint, not a group of tasks. due_date is the forecast (the current best guess);
-- baseline_date is what was first promised, so slippage can be seen. outcome is a decision made by the project's lead or
-- a manager (achieved or missed), never worked out from the tasks. See ADDED_COLUMNS for the rest.
CREATE TABLE IF NOT EXISTS milestones (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id INTEGER NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  due_date TEXT,
  completed_at TEXT,
  position INTEGER NOT NULL DEFAULT 0
);
-- Each change of a milestone's forecast date, with the reason given.
CREATE TABLE IF NOT EXISTS milestone_moves (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  milestone_id INTEGER NOT NULL REFERENCES milestones(id) ON DELETE CASCADE,
  user_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  from_date TEXT,
  to_date TEXT,
  reason TEXT NOT NULL DEFAULT '',
  created_at TEXT NOT NULL DEFAULT (to_char(timezone('UTC', now()), 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'))
);
-- "milestone_id can't be achieved before depends_on_id": both belong to the same project.
CREATE TABLE IF NOT EXISTS milestone_deps (
  milestone_id INTEGER NOT NULL REFERENCES milestones(id) ON DELETE CASCADE,
  depends_on_id INTEGER NOT NULL REFERENCES milestones(id) ON DELETE CASCADE,
  PRIMARY KEY (milestone_id, depends_on_id),
  CHECK (milestone_id != depends_on_id)
);
CREATE TABLE IF NOT EXISTS tags (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  UNIQUE (user_id, name)
);
CREATE TABLE IF NOT EXISTS tasks (
